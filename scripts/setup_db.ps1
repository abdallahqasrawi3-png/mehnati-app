<#
  Starts the local PostgreSQL cluster used by Mehnaty. On the first run it also:
    - creates the cluster in %LOCALAPPDATA%\Mehnaty\pgdata (ASCII path, user-owned, no admin rights)
    - creates the "mehnaty" role and database with random passwords
    - writes backend\.env (never committed) with those credentials
  If you already have your own PostgreSQL server, skip this: fill backend\.env (see .env.example)
  and set MEHNATY_EXTERNAL_DB=1 before running start.bat.
#>
param([Parameter(Mandatory = $true)][string]$PgBin)

$ErrorActionPreference = 'Continue'
$Root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
$EnvFile = Join-Path $Root 'backend\.env'
$DataRoot = Join-Path $env:LOCALAPPDATA 'Mehnaty'
$Data = Join-Path $DataRoot 'pgdata'
$Log = Join-Path $DataRoot 'postgres.log'
$Done = Join-Path $DataRoot 'setup.complete'
$Port = 5432

if ($env:MEHNATY_EXTERNAL_DB -eq '1') { Write-Host 'Using external database from backend\.env'; exit 0 }

function NewSecret([int]$n) { -join ((48..57) + (65..90) + (97..122) | Get-Random -Count $n | ForEach-Object { [char]$_ }) }
function IsReady { & (Join-Path $PgBin 'pg_isready.exe') -h localhost -p $Port -q; return ($LASTEXITCODE -eq 0) }
function StopOurServer {
  if (Test-Path (Join-Path $Data 'postmaster.pid')) {
    Start-Process -FilePath (Join-Path $PgBin 'pg_ctl.exe') -ArgumentList '-D', "`"$Data`"", 'stop', '-m', 'fast' -WindowStyle Hidden -Wait
  }
}
function StartServer {
  # Detached start: piping pg_ctl's output would keep this script waiting forever.
  Start-Process -FilePath (Join-Path $PgBin 'pg_ctl.exe') -WindowStyle Hidden `
    -ArgumentList '-D', "`"$Data`"", '-l', "`"$Log`"", '-o', "`"-p $Port -c listen_addresses=localhost`"", 'start' | Out-Null
  for ($i = 0; $i -lt 60; $i++) { if (IsReady) { return $true }; Start-Sleep -Milliseconds 500 }
  return $false
}

$firstRun = -not (Test-Path $Done)
if ($firstRun) {
  if (Test-Path $Data) {
    Write-Host 'Removing an unfinished database folder from an earlier attempt...'
    StopOurServer
    Start-Sleep 1
    Remove-Item $Data -Recurse -Force
  }
  if (IsReady) {
    Write-Host "Another PostgreSQL server is already running on port $Port." -ForegroundColor Yellow
    Write-Host 'Either stop it, or put its credentials in backend\.env and set MEHNATY_EXTERNAL_DB=1.' -ForegroundColor Yellow
    exit 1
  }
  Write-Host "First run: creating database cluster in $Data"
  New-Item -ItemType Directory -Force $DataRoot | Out-Null
  $superPw = NewSecret 24
  $pwFile = Join-Path $DataRoot 'superuser.tmp'
  Set-Content -Path $pwFile -Value $superPw -NoNewline -Encoding ascii
  # locale C avoids initdb failures on Windows systems with non-English locales
  & (Join-Path $PgBin 'initdb.exe') --pgdata="$Data" --username=postgres --encoding=UTF8 --locale=C --pwfile="$pwFile" --auth=scram-sha-256 | Out-Null
  $code = $LASTEXITCODE
  Remove-Item $pwFile -Force
  if ($code -ne 0) { Write-Host 'initdb failed.' -ForegroundColor Red; exit 1 }
}

if (-not (IsReady)) {
  if (-not (StartServer)) { Write-Host "PostgreSQL did not start. See $Log" -ForegroundColor Red; exit 1 }
}
Write-Host "PostgreSQL is running on localhost:$Port"

if ($firstRun) {
  $appPw = NewSecret 24
  $env:PGPASSWORD = $superPw
  & (Join-Path $PgBin 'psql.exe') -h localhost -p $Port -U postgres -d postgres -v ON_ERROR_STOP=1 -q `
    -c "CREATE ROLE mehnaty LOGIN CREATEDB PASSWORD '$appPw';" `
    -c "CREATE DATABASE mehnaty OWNER mehnaty ENCODING 'UTF8' TEMPLATE template0;"
  $code = $LASTEXITCODE
  Remove-Item Env:\PGPASSWORD
  if ($code -ne 0) { Write-Host 'Could not create the database.' -ForegroundColor Red; exit 1 }
  $secret = NewSecret 50
  $content = @"
# Generated by scripts\setup_db.ps1 for local development. Do not commit.
DJANGO_DEBUG=true
DJANGO_SECRET_KEY=$secret
DJANGO_ALLOWED_HOSTS=*
DB_NAME=mehnaty
DB_USER=mehnaty
DB_PASSWORD=$appPw
DB_HOST=localhost
DB_PORT=$Port
ANTHROPIC_API_KEY=
AI_MODEL=claude-opus-5-5
SHIPPING_SIMULATOR_ENABLED=false
"@
  if (Test-Path $EnvFile) { Copy-Item $EnvFile "$EnvFile.bak" -Force; Write-Host 'Existing backend\.env saved as .env.bak' }
  [IO.File]::WriteAllText($EnvFile, $content, (New-Object Text.UTF8Encoding($false)))
  Set-Content -Path $Done -Value (Get-Date -Format s) -Encoding ascii
  Write-Host 'Created database "mehnaty" and backend\.env'
}
exit 0
